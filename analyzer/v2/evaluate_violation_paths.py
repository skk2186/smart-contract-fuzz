#!/usr/bin/env python3

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

from abstract_interpreter import (
    simulate_path,
)


def parse_sequence(
    source: str,
) -> list[str]:
    return [
        item.strip()
        for item in re.split(
            r"\s*->\s*",
            source.strip(),
        )
        if item.strip()
    ]


def choose_property(
    model: dict[str, Any],
    requested: str | None,
) -> str:
    properties = model.get(
        "properties",
        {},
    )

    if requested:
        if requested not in properties:
            raise ValueError(
                f"Property {requested!r} not found. "
                f"Available: {sorted(properties)}"
            )

        return requested

    if len(properties) != 1:
        raise ValueError(
            "The model contains multiple properties; "
            "--property is required."
        )

    return next(iter(properties))


def load_candidate_sequences(
    path: Path,
    contract_name: str | None,
) -> list[list[str]]:
    data = json.loads(
        path.read_text(encoding="utf-8")
    )

    container: Any = data

    if contract_name:
        container = data.get(
            contract_name,
            {},
        )

    if isinstance(container, dict):
        paths = container.get(
            "paths",
            [],
        )
    else:
        paths = []

    result: list[list[str]] = []

    for item in paths:
        if not isinstance(item, dict):
            continue

        sequence = item.get("sequence")

        if (
            isinstance(sequence, list)
            and all(
                isinstance(value, str)
                for value in sequence
            )
        ):
            result.append(sequence)

    return result


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Classify candidate paths according to "
            "an Echidna property's violation predicate."
        )
    )

    parser.add_argument(
        "model",
        type=Path,
        help=(
            "JSON generated by "
            "extract_property_predicate.py"
        ),
    )

    parser.add_argument(
        "--property",
    )

    parser.add_argument(
        "--sequence",
        action="append",
        default=[],
        help=(
            "Function signatures separated by ->. "
            "May be supplied multiple times."
        ),
    )

    parser.add_argument(
        "--paths",
        type=Path,
        help=(
            "Existing candidate-path JSON."
        ),
    )

    parser.add_argument(
        "--contract",
        help=(
            "Contract key inside candidate-path JSON."
        ),
    )

    parser.add_argument(
        "--output",
        type=Path,
    )

    return parser.parse_args()


def main() -> None:
    arguments = parse_arguments()

    model = json.loads(
        arguments.model.read_text(
            encoding="utf-8"
        )
    )

    property_name = choose_property(
        model,
        arguments.property,
    )

    sequences = [
        parse_sequence(source)
        for source in arguments.sequence
    ]

    if arguments.paths:
        sequences.extend(
            load_candidate_sequences(
                arguments.paths,
                arguments.contract,
            )
        )

    if not sequences:
        raise SystemExit(
            "No candidate sequences supplied."
        )

    results = []

    for rank, sequence in enumerate(
        sequences,
        start=1,
    ):
        result = simulate_path(
            model,
            property_name,
            sequence,
        )

        result["input_rank"] = rank
        results.append(result)

    output = {
        "schema_version": "2.0",
        "method_version": (
            "Full-v2.0-core-1B"
        ),
        "contract": model.get(
            "contract",
            "",
        ),
        "property": property_name,
        "results": results,
    }

    serialized = json.dumps(
        output,
        ensure_ascii=False,
        indent=2,
    )

    if arguments.output:
        arguments.output.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        arguments.output.write_text(
            serialized + "\n",
            encoding="utf-8",
            newline="\n",
        )
    else:
        sys.stdout.write(
            serialized + "\n"
        )


if __name__ == "__main__":
    main()
